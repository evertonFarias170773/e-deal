-- =====================================================================================
-- SEÇÃO E — RPCs que gravam em movimento_credito SEM passar por uma linha de
--   conta_corrente_pendencias (crédito/débito avulso — origem=AJUSTE/SISTEMA,
--   id_pendencia NULL). Existem para que o cutover (1b) possa revogar
--   INSERT/UPDATE/DELETE diretos em movimento_credito para `anon` e
--   `authenticated` sem quebrar os fluxos que gravam na razão fora do fluxo
--   de pendências:
--     1) ajuste-credito (avulso, admin/superadmin)      → mc_ajuste_avulso_criar
--     2) estorno-credito (avulso, admin/superadmin)     → mc_ajuste_avulso_estornar
--     3) confirmar (fallback [ABATIMENTO_DEBITO:x] de
--        cobranças anteriores a este refactor)          → mc_confirmar_abatimento_legado
--     4) usar-credito (consumo de crédito avulso como
--        E-Crédito — NÃO é legado, é caminho ativo:      → mc_usar_credito_avulso
--        ver correção da divergência de saldo abaixo)
--   Após o cutover, TODA gravação em movimento_credito ocorre exclusivamente
--   por RPC SECURITY DEFINER — nenhuma mais por INSERT/UPDATE direto do cliente.
-- =====================================================================================

-- E.1 — Ajuste avulso: criação (substitui INSERT direto + dedup por janela de
-- 60s em registrarMovimento/ajuste-credito). Idempotência por chave persistida.
CREATE OR REPLACE FUNCTION public.mc_ajuste_avulso_criar(
  p_id_cliente bigint, p_tipo text, p_valor numeric, p_observacao text, p_chave_idempotencia uuid)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_existente bigint;
  v_new_id bigint;
BEGIN
  PERFORM public.cc__assert_permissao(v_uid, '__ADMIN__');   -- mesma regra da rota atual: admin/superadmin
  IF p_id_cliente IS NULL OR p_tipo IS NULL OR p_valor IS NULL OR p_chave_idempotencia IS NULL THEN
    RAISE EXCEPTION 'MC_PARAMS: id_cliente, tipo, valor e chave_idempotencia são obrigatórios';
  END IF;
  IF p_tipo NOT IN ('CREDITO','DEBITO') THEN RAISE EXCEPTION 'MC_TIPO: tipo inválido % (use CREDITO ou DEBITO)', p_tipo; END IF;
  IF p_valor <= 0 THEN RAISE EXCEPTION 'MC_VALOR: valor deve ser maior que zero'; END IF;
  IF p_observacao IS NULL OR btrim(p_observacao) = '' THEN RAISE EXCEPTION 'MC_OBS: observação é obrigatória para este ajuste'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.clientes WHERE id_cliente = p_id_cliente) THEN
    RAISE EXCEPTION 'MC_CLIENTE: cliente % não encontrado', p_id_cliente;
  END IF;

  SELECT id INTO v_existente FROM public.movimento_credito WHERE chave_idempotencia = p_chave_idempotencia;
  IF FOUND THEN RETURN v_existente; END IF;

  INSERT INTO public.movimento_credito
    (id_cliente, id_int, valor, tipo, origem, observacao, created_by, cancelado, chave_idempotencia)
  VALUES (p_id_cliente, NULL, round(p_valor,2), p_tipo, 'AJUSTE', btrim(p_observacao), v_uid, false, p_chave_idempotencia)
  RETURNING id INTO v_new_id;

  RETURN v_new_id;
END; $$;

-- E.2 — Ajuste avulso: estorno por lançamento compensatório (substitui INSERT
-- direto em estornarMovimentoCredito/estorno-credito). Escopo restrito a
-- movimentos avulsos (origem=AJUSTE, sem proposta) — movimentos vinculados a
-- pendência são estornados por cc_encerrar_pendencia(ESTORNO), não por aqui.
-- Idempotência já garantida por ux_mc_estorno_unico (id_movimento_ref único).
CREATE OR REPLACE FUNCTION public.mc_ajuste_avulso_estornar(p_id_movimento bigint, p_observacao text DEFAULT NULL)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_mov public.movimento_credito%ROWTYPE;
  v_existente bigint;
  v_saldo numeric;
  v_new_id bigint;
BEGIN
  PERFORM public.cc__assert_permissao(v_uid, '__ADMIN__');   -- v1: somente admin/superadmin
  IF p_id_movimento IS NULL THEN RAISE EXCEPTION 'MC_PARAMS: id_movimento é obrigatório'; END IF;

  SELECT * INTO v_mov FROM public.movimento_credito WHERE id = p_id_movimento FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'MC_NAOENCONTRADO: movimento % não encontrado', p_id_movimento; END IF;
  IF v_mov.origem <> 'AJUSTE' OR v_mov.id_int IS NOT NULL THEN
    RAISE EXCEPTION 'MC_ESCOPO: apenas movimentos avulsos (origem=AJUSTE, sem proposta) podem ser estornados por esta função';
  END IF;
  -- Legado: registros cancelados pelo mecanismo antigo (UPDATE cancelado=true,
  -- anterior à correção para lançamento compensatório) não podem ser reestornados.
  IF v_mov.cancelado THEN RAISE EXCEPTION 'MC_CANCELADO: movimento já está cancelado'; END IF;

  SELECT id INTO v_existente FROM public.movimento_credito
   WHERE id_movimento_ref = p_id_movimento AND tipo_evento = 'ESTORNO';
  IF FOUND THEN RETURN v_existente; END IF;

  IF v_mov.tipo = 'CREDITO' THEN
    SELECT COALESCE(SUM(CASE WHEN tipo = 'CREDITO' THEN valor WHEN tipo = 'DEBITO' THEN -valor ELSE 0 END), 0)
      INTO v_saldo
      FROM public.movimento_credito
     WHERE id_cliente = v_mov.id_cliente AND cancelado = false;
    IF GREATEST(v_saldo, 0) - v_mov.valor < 0 THEN
      RAISE EXCEPTION 'MC_SALDO_INSUFICIENTE: saldo atual (R$ %) insuficiente para estornar R$ % — pode já ter sido utilizado', GREATEST(v_saldo,0), v_mov.valor;
    END IF;
  END IF;

  INSERT INTO public.movimento_credito (id_cliente, id_int, valor, tipo, origem, observacao, created_by,
         id_movimento_ref, tipo_evento)
  VALUES (v_mov.id_cliente, v_mov.id_int, v_mov.valor,
         CASE WHEN v_mov.tipo = 'CREDITO' THEN 'DEBITO' ELSE 'CREDITO' END,
         'AJUSTE', COALESCE(p_observacao, format('Estorno do movimento #%s.', p_id_movimento)), v_uid,
         p_id_movimento, 'ESTORNO')
  RETURNING id INTO v_new_id;

  RETURN v_new_id;
END; $$;

-- E.2b — Consumo de crédito AVULSO (origem=AJUSTE/SISTEMA, sem pendência)
-- como pagamento de proposta (E-Crédito). Corrige a divergência entre o
-- saldo total exibido no banner/modal (getSaldoCredito/getSaldoContaCorrente,
-- que somam TODA a razão do cliente) e o saldo que
-- /api/cobrancas/usar-credito conseguia efetivamente consumir (que só
-- enxergava conta_corrente_pendencias: um cliente com crédito 100% avulso
-- (lançado por mc_ajuste_avulso_criar, sem nenhuma pendência aberta) fazia o
-- servidor calcular R$ 0,00 disponível, e a cobrança falhava com "Saldo
-- insuficiente" mesmo o banner mostrando saldo > 0).
--
-- Mesma permissão de cc_usar_pendencia(CREDITO_IMEDIATO): 'credito.usar' —
-- consumir crédito já existente não é operação administrativa como CRIAR ou
-- ESTORNAR um ajuste (mc_ajuste_avulso_criar/estornar exigem __ADMIN__).
--
-- p_id_pagamento é OBRIGATÓRIO (não tem DEFAULT — precisa vir antes dos
-- parâmetros opcionais na assinatura). A linha é travada com FOR UPDATE antes
-- de qualquer decisão: mesma regra "nunca UPDATE/decide às cegas" já usada em
-- cc_usar_pendencia(RESERVA_DEBITO) para pagamentos_v2 — rejeita CANCELADO e
-- valida cliente/proposta/empresa contra a linha travada, nunca só o payload.
--
-- Idempotência por id_pagamento_destino: se este pagamento já tem um
-- USO_PEDIDO avulso (tipo_evento='USO_PEDIDO' AND id_pendencia IS NULL — a
-- marca exclusiva desta função; USO_PEDIDO de cc_usar_pendencia sempre tem
-- id_pendencia preenchido, nunca colide), retorna o movimento existente sem
-- debitar de novo. Checada antes das demais validações de negócio: uma
-- repetição de operação já concluída deve retornar sucesso mesmo que o
-- pagamento tenha mudado de estado depois.
--
-- Não há uma linha de saldo dedicada para crédito avulso (diferente de
-- conta_corrente_pendencias.valor_saldo, mantida por FOR UPDATE na própria
-- linha) — por isso trava também o cliente (public.clientes) para serializar
-- concorrência ENTRE pagamentos diferentes do mesmo cliente (o lock em
-- pagamentos_v2 só serializa chamadas repetidas para o MESMO pagamento).
-- Recalcula o saldo real de TODA a razão sob a trava do cliente (mesma
-- fórmula de getSaldoCredito/getSaldoContaCorrente) e só então grava o
-- DEBITO — impede duplo uso mesmo em requisições concorrentes.
CREATE OR REPLACE FUNCTION public.mc_usar_credito_avulso(
  p_id_cliente bigint, p_valor numeric, p_id_pagamento uuid,
  p_id_int_destino bigint DEFAULT NULL, p_observacao text DEFAULT NULL)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_valor numeric;
  v_saldo numeric;
  v_pag public.pagamentos_v2%ROWTYPE;
  v_existente bigint;
  v_new_id bigint;
BEGIN
  PERFORM public.cc__assert_permissao(v_uid, 'credito.usar');
  IF p_id_cliente IS NULL OR p_valor IS NULL OR p_id_pagamento IS NULL THEN
    RAISE EXCEPTION 'MC_PARAMS: id_cliente, valor e id_pagamento são obrigatórios';
  END IF;
  v_valor := round(p_valor, 2);
  IF v_valor < 0.01 THEN RAISE EXCEPTION 'CC_VALOR_MINIMO: uso mínimo é R$ 0,01'; END IF;

  SELECT * INTO v_pag FROM public.pagamentos_v2 WHERE id = p_id_pagamento FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'CC_COBRANCA: pagamento % não encontrado', p_id_pagamento; END IF;

  SELECT id INTO v_existente FROM public.movimento_credito
   WHERE id_pagamento_destino = p_id_pagamento
     AND tipo_evento = 'USO_PEDIDO'
     AND id_pendencia IS NULL;
  IF FOUND THEN RETURN v_existente; END IF;

  IF v_pag.status = 'CANCELADO' THEN
    RAISE EXCEPTION 'CC_COBRANCA_CANCELADA: pagamento % está cancelado', p_id_pagamento;
  END IF;
  IF v_pag.id_cliente IS DISTINCT FROM p_id_cliente THEN
    RAISE EXCEPTION 'CC_CLIENTE_DIVERGENTE: pagamento % pertence a outro cliente', p_id_pagamento;
  END IF;
  IF p_id_int_destino IS NOT NULL AND v_pag.id_int IS DISTINCT FROM p_id_int_destino THEN
    RAISE EXCEPTION 'CC_PROPOSTA_DIVERGENTE: pagamento % não pertence à proposta de destino informada', p_id_pagamento;
  END IF;
  IF v_pag.id_empresa IS NOT NULL AND v_pag.id_empresa <> public.cc__id_empresa_proposta(v_pag.id_int) THEN
    RAISE EXCEPTION 'CC_EMPRESA_DIVERGENTE: pagamento % pertence a outra empresa', p_id_pagamento;
  END IF;

  PERFORM 1 FROM public.clientes WHERE id_cliente = p_id_cliente FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'MC_CLIENTE: cliente % não encontrado', p_id_cliente; END IF;

  SELECT COALESCE(SUM(CASE WHEN tipo = 'CREDITO' THEN valor WHEN tipo = 'DEBITO' THEN -valor ELSE 0 END), 0)
    INTO v_saldo
    FROM public.movimento_credito
   WHERE id_cliente = p_id_cliente AND cancelado = false;

  IF v_saldo < v_valor THEN
    RAISE EXCEPTION 'CC_SALDO_INSUFICIENTE: saldo R$ % < solicitado R$ %', GREATEST(v_saldo,0), v_valor;
  END IF;

  INSERT INTO public.movimento_credito (id_cliente, id_int, valor, tipo, origem, observacao, created_by,
         tipo_evento, id_int_destino, id_pagamento_destino, motivo_evento)
  VALUES (p_id_cliente, v_pag.id_int, v_valor, 'DEBITO', 'SISTEMA',
         COALESCE(p_observacao, 'Crédito avulso aplicado como pagamento.'), v_uid,
         'USO_PEDIDO', v_pag.id_int, p_id_pagamento, 'USO_CREDITO_AVULSO')
  RETURNING id INTO v_new_id;

  PERFORM public.cc__timeline(v_pag.id_int, p_id_cliente,
    format('💰 Crédito avulso de R$ %s aplicado como pagamento.', to_char(v_valor,'FM999999990.00')), v_uid);

  RETURN v_new_id;
END; $$;

-- E.3 — Fallback legado de abatimento de débito em /api/cobrancas/confirmar
-- (cobranças criadas com o marcador [ABATIMENTO_DEBITO:x] antes deste
-- refactor, sem reserva formal via cc_usar_pendencia). Substitui o INSERT
-- direto + verificação por `ilike observacao` por uma chave determinística
-- persistida (o próprio id do pagamento, já único) via ux_mc_abatimento_legado_unico.
CREATE OR REPLACE FUNCTION public.mc_confirmar_abatimento_legado(
  p_id_cliente bigint, p_id_int bigint, p_id_pagamento uuid, p_valor numeric, p_observacao text)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_existente bigint;
  v_new_id bigint;
BEGIN
  PERFORM public.cc__assert_permissao(v_uid, 'conferencia.confirm');
  IF p_id_cliente IS NULL OR p_id_pagamento IS NULL OR p_valor IS NULL THEN
    RAISE EXCEPTION 'MC_PARAMS: id_cliente, id_pagamento e valor são obrigatórios';
  END IF;
  IF p_valor <= 0 THEN RAISE EXCEPTION 'MC_VALOR: valor deve ser maior que zero'; END IF;

  SELECT id INTO v_existente FROM public.movimento_credito
   WHERE id_pagamento_destino = p_id_pagamento AND tipo_evento = 'ABATIMENTO_LEGADO';
  IF FOUND THEN RETURN v_existente; END IF;

  INSERT INTO public.movimento_credito (id_cliente, id_int, valor, tipo, origem, observacao, created_by,
         tipo_evento, id_pagamento_destino)
  VALUES (p_id_cliente, p_id_int, round(p_valor,2), 'CREDITO', 'SISTEMA', p_observacao, v_uid,
         'ABATIMENTO_LEGADO', p_id_pagamento)
  RETURNING id INTO v_new_id;

  IF p_id_int IS NOT NULL THEN
    PERFORM public.cc__timeline(p_id_int, p_id_cliente,
      format('💳 Débito de R$ %s abatido na conta corrente após confirmação do pagamento.', to_char(round(p_valor,2),'FM999999990.00')), v_uid);
  END IF;

  RETURN v_new_id;
END; $$;

