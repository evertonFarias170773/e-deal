-- Valor pago confirmado da proposta (recalculado no servidor; NÃO usa propostas.valor_total)
CREATE OR REPLACE FUNCTION public.cc__valor_pago(p_id_int bigint)
RETURNS numeric LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
  SELECT COALESCE(round(SUM(
    GREATEST(0, COALESCE(valor,0) - COALESCE(
      (regexp_match(COALESCE(obs_v2,''), '\[ABATIMENTO_DEBITO:(\d+(?:\.\d{1,2})?)\]'))[1]::numeric, 0)))
  , 2), 0)
  FROM public.pagamentos_v2
  WHERE id_int = p_id_int
    AND status <> 'CANCELADO'
    AND (status = 'PAID' OR (status = 'A_VENCER' AND confirmado = true));
$$;

-- Resolve o id_empresa numérico (mesmo espaço de public.usuarios.id_empresa)
-- a partir de pagamentos_v2.id_empresa — a mesma fonte já usada por todo o
-- domínio financeiro (gerar-pix, cancelar-boleto, cancelar-externo), em vez
-- de propostas.empresa (texto livre, frequentemente NULL — ex.: proposta
-- #18087, que travava em editar-paga com "empresa inválida ou não
-- reconhecida ('null')"). Considera apenas cobranças não CANCELADAS da
-- proposta; se houver exatamente uma empresa entre elas, usa-a; se não
-- houver nenhuma ou houver mais de uma distinta, retorna NULL (os
-- chamadores — cc__assert_escopo_empresa e a policy RLS — já tratam NULL
-- como "fora do escopo"/sem acesso).
CREATE OR REPLACE FUNCTION public.cc__id_empresa_proposta(p_id_int bigint)
RETURNS bigint LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
  SELECT CASE WHEN count(DISTINCT id_empresa) = 1 THEN min(id_empresa) ELSE NULL END
  FROM public.pagamentos_v2
  WHERE id_int = p_id_int
    AND status <> 'CANCELADO'
    AND id_empresa IS NOT NULL;
$$;

-- =====================================================================================
-- SEÇÃO D.0b — Policy de conta_corrente_pendencias (RLS por escopo de empresa)
--   Substitui o USING(true) provisório da Seção A agora que
--   cc__id_empresa_proposta existe. Superadmin acessa tudo; demais usuários
--   só veem pendências de propostas da própria empresa (mesma regra oficial
--   de escopo de empresa/proposta já usada no projeto).
-- =====================================================================================
CREATE POLICY ccp_select_authenticated ON public.conta_corrente_pendencias
  FOR SELECT TO authenticated USING (
    EXISTS (
      SELECT 1 FROM public.usuarios u
      WHERE u.user_id = auth.uid()
        AND (
          COALESCE(u.is_super_adm, false)
          OR (u.id_empresa IS NOT NULL AND u.id_empresa = public.cc__id_empresa_proposta(conta_corrente_pendencias.id_int))
        )
    )
  );

-- Escopo de empresa oficial (mesma regra já usada em cancelar-boleto/route.ts
-- e cancelar-externo/route.ts para pagamentos_v2, aqui estendida a
-- propostas via cc__id_empresa_proposta): superadmin acessa tudo; qualquer
-- outro usuário só age sobre uma proposta cujo id_empresa resolvido bate com
-- usuarios.id_empresa. RAISE em caso de fora de escopo — nunca retorna
-- boolean para o chamador decidir (evita esquecer de checar o retorno).
CREATE OR REPLACE FUNCTION public.cc__assert_escopo_empresa(p_uid uuid, p_id_int bigint)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  v_super public.usuarios.is_super_adm%TYPE;
  v_empresa_usuario public.usuarios.id_empresa%TYPE;
  v_empresa_proposta bigint;
BEGIN
  SELECT is_super_adm, id_empresa INTO v_super, v_empresa_usuario
    FROM public.usuarios WHERE user_id = p_uid;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'AUTH: usuário sem cadastro em public.usuarios' USING ERRCODE = '28000';
  END IF;
  IF COALESCE(v_super, false) THEN RETURN; END IF;

  v_empresa_proposta := public.cc__id_empresa_proposta(p_id_int);
  IF v_empresa_usuario IS NULL OR v_empresa_proposta IS NULL OR v_empresa_usuario <> v_empresa_proposta THEN
    RAISE EXCEPTION 'PERM: proposta #% fora do escopo de empresa do usuário', p_id_int USING ERRCODE = '42501';
  END IF;
END; $$;

-- Recalcula no banco o total soberano da proposta (mesma fórmula de
-- calculateResumo()/saveProposta() em orcamentos.service.ts e
-- orcamento-utils.ts — NÃO uma regra nova):
--   não-avulso: valorTotal = max(0, subtotalItensAtivos - descontoGeral + frete)
--     subtotalItensAtivos = SUM(produtos_proposta.valor_sub_total)
--       WHERE COALESCE(status_item,'PENDENTE') <> 'CANCELADO'
--     descontoGeral = min(subtotal, max(0, PERCENTUAL: subtotal*valor_percentual/100 | VALOR: valor_nominal))
--       fonte: desconto_proposta (tipo_desconto='DESCONTO_GERAL' ou NULL —
--       linhas legadas sem o tipo marcado também são desconto geral)
--     frete = propostas.valor_frete (frete já escolhido/persistido na proposta)
--   avulso: valorTotal = max(0, propostas.valor + propostas.valor_frete) — sem
--     itens em produtos_proposta e sem desconto geral, mesma regra do ramo
--     avulso de saveProposta/getPropostaDetailById.
CREATE OR REPLACE FUNCTION public.cc__total_soberano_proposta(p_id_int bigint)
RETURNS numeric LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  v_prop public.propostas%ROWTYPE;
  v_subtotal numeric;
  v_frete numeric;
  v_desc_pct numeric;
  v_desc_nom numeric;
  v_desconto numeric;
BEGIN
  SELECT * INTO v_prop FROM public.propostas WHERE id_int = p_id_int;
  IF NOT FOUND THEN RETURN NULL; END IF;

  v_frete := COALESCE(v_prop.valor_frete, 0);

  IF v_prop.is_avulso THEN
    RETURN GREATEST(0, round(COALESCE(v_prop.valor, 0) + v_frete, 2));
  END IF;

  SELECT COALESCE(SUM(valor_sub_total), 0) INTO v_subtotal
    FROM public.produtos_proposta
   WHERE id_int = p_id_int
     AND COALESCE(status_item, 'PENDENTE') <> 'CANCELADO';

  -- 'DESCONTO_GERAL' é o único tipo gravado pelo código (orcamentos.service.ts);
  -- tipo_desconto NULL ocorre em linhas legadas com o mesmo formato/uso (ex.:
  -- proposta #18087, desconto_proposta.id=75, tipo_desconto=NULL, descricao=
  -- 'Tabela especial') e precisa ser tratado como o mesmo desconto geral —
  -- caso contrário o helper ignora um desconto que o front já aplica (bug
  -- que causou CC_TOTAL_DIVERGENTE: informado R$3.741,50 x recalculado
  -- R$3.919,00, diferença de R$177,50 = 5% de R$3.550,00 do desconto perdido).
  SELECT valor_percentual, valor_nominal INTO v_desc_pct, v_desc_nom
    FROM public.desconto_proposta
   WHERE id_int = p_id_int AND (tipo_desconto = 'DESCONTO_GERAL' OR tipo_desconto IS NULL)
   ORDER BY (tipo_desconto = 'DESCONTO_GERAL') DESC, id DESC
   LIMIT 1;

  IF COALESCE(v_desc_pct, 0) > 0 THEN
    v_desconto := GREATEST(0, v_subtotal * v_desc_pct / 100);
  ELSE
    v_desconto := GREATEST(0, COALESCE(v_desc_nom, 0));
  END IF;
  v_desconto := LEAST(v_subtotal, v_desconto);

  RETURN GREATEST(0, round(v_subtotal + v_frete - v_desconto, 2));
END; $$;

-- =====================================================================================
-- SEÇÃO D.1 — RPC: cc_abrir_pendencia
-- =====================================================================================
CREATE OR REPLACE FUNCTION public.cc_abrir_pendencia(
  p_id_int bigint, p_id_cliente bigint, p_chave_evento uuid,
  p_motivo text, p_total_soberano numeric, p_observacao text DEFAULT NULL)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_exist bigint; v_prop_cliente bigint;
  v_pago numeric; v_diff numeric; v_dir text; v_new numeric;
  v_open public.conta_corrente_pendencias%ROWTYPE;
  v_committed numeric; v_delta numeric; v_tipo text; v_new_id bigint;
  v_total_recalculado numeric;
BEGIN
  PERFORM public.cc__assert_permissao(v_uid, 'propostas.editar_paga');
  IF p_id_int IS NULL OR p_id_cliente IS NULL OR p_chave_evento IS NULL OR p_motivo IS NULL THEN
    RAISE EXCEPTION 'CC_PARAMS: id_int, id_cliente, chave_evento e motivo são obrigatórios';
  END IF;

  SELECT id INTO v_exist FROM public.conta_corrente_pendencias WHERE chave_evento = p_chave_evento;
  IF FOUND THEN RETURN v_exist; END IF;

  SELECT id_cliente INTO v_prop_cliente FROM public.propostas WHERE id_int = p_id_int;
  IF NOT FOUND THEN RAISE EXCEPTION 'CC_PROPOSTA: proposta #% não encontrada', p_id_int; END IF;

  -- p_id_cliente deve corresponder ao cliente real da proposta, nunca só o
  -- valor que o chamador informou.
  IF v_prop_cliente IS DISTINCT FROM p_id_cliente THEN
    RAISE EXCEPTION 'CC_CLIENTE: id_cliente informado (%) não corresponde ao cliente real da proposta #% (%)', p_id_cliente, p_id_int, v_prop_cliente;
  END IF;

  -- Escopo de empresa do usuário (mesma regra oficial já usada no projeto).
  PERFORM public.cc__assert_escopo_empresa(v_uid, p_id_int);

  v_pago := public.cc__valor_pago(p_id_int);

  -- A pendência só existe para diferença surgida DEPOIS que a proposta já
  -- está paga — sem pagamento confirmado não há "diferença" a registrar.
  IF v_pago <= 0 THEN
    RAISE EXCEPTION 'CC_NAO_PAGA: proposta #% não possui pagamento confirmado — Conta Corrente só se aplica a diferença após proposta paga', p_id_int;
  END IF;

  -- Não confia isoladamente em p_total_soberano: recalcula no banco (itens
  -- não CANCELADOS + frete escolhido + desconto geral) e rejeita divergência
  -- além de tolerância de arredondamento (R$ 0,02 — mesma tolerância já
  -- usada em resolver-diferenca/route.ts).
  v_total_recalculado := public.cc__total_soberano_proposta(p_id_int);
  IF v_total_recalculado IS NULL THEN
    RAISE EXCEPTION 'CC_TOTAL_INDISPONIVEL: não foi possível recalcular o total da proposta #%', p_id_int;
  END IF;
  IF abs(v_total_recalculado - p_total_soberano) > 0.02 THEN
    RAISE EXCEPTION 'CC_TOTAL_DIVERGENTE: total informado (R$ %) diverge do recalculado no banco (R$ %) para a proposta #%', p_total_soberano, v_total_recalculado, p_id_int;
  END IF;

  v_diff := round(p_total_soberano - v_pago, 2);
  v_dir  := CASE WHEN v_diff < 0 THEN 'FAVOR_CLIENTE' WHEN v_diff > 0 THEN 'FAVOR_EMPRESA' ELSE NULL END;
  v_new  := abs(v_diff);

  -- REGRA (2026-07-22): diferença DEVEDORA (novo total > pago) é saldo da
  -- própria proposta — resolvida por cobrança complementar, abono do
  -- administrador ou E-Crédito — e NUNCA entra na Conta Corrente. Trata como
  -- diferença zero para fins de pendência: encerra pendência aberta (se nada
  -- comprometido) e não cria pendência FAVOR_EMPRESA a partir deste fluxo.
  IF v_diff > 0 THEN
    v_dir := NULL;
    v_new := 0;
  END IF;

  SELECT * INTO v_open FROM public.conta_corrente_pendencias
   WHERE id_int = p_id_int AND status IN ('ABERTA','PARCIALMENTE_RESOLVIDA')
   FOR UPDATE;

  IF FOUND THEN
    v_committed := v_open.valor_reservado + (v_open.valor_original - v_open.valor_saldo - v_open.valor_reservado);
    IF v_dir IS NULL OR v_dir = v_open.direcao THEN
      IF v_new < 0.01 THEN
        IF v_committed > 0 THEN
          RAISE EXCEPTION 'CC_AJUSTE_ABAIXO_COMPROMETIDO: diferença zerada mas há valor já usado/reservado (R$ %) — revisão do financeiro necessária', v_committed;
        END IF;
        IF v_open.valor_saldo > 0 THEN
          INSERT INTO public.movimento_credito (id_cliente, id_int, valor, tipo, origem, observacao, created_by,
                 id_pendencia, tipo_evento, id_int_origem, motivo_evento)
          VALUES (p_id_cliente, p_id_int, v_open.valor_saldo,
                 CASE WHEN v_open.direcao = 'FAVOR_CLIENTE' THEN 'DEBITO' ELSE 'CREDITO' END,
                 'SISTEMA', 'Diferença zerada após nova alteração da proposta.', v_uid,
                 v_open.id, 'CANCELAMENTO', p_id_int, 'DIFERENCA_ZERADA');
        END IF;
        UPDATE public.conta_corrente_pendencias
           SET valor_saldo = 0, status = 'CANCELADA', encerrado_em = now(), encerrado_por = v_uid,
               motivo_encerramento = 'DIFERENCA_ZERADA', atualizado_em = now()
         WHERE id = v_open.id;
        PERFORM public.cc__timeline(p_id_int, p_id_cliente,
          '✔️ Pendência encerrada: diferença financeira zerada após nova alteração.', v_uid);
        RETURN v_open.id;
      END IF;
      IF v_new < v_committed - 0.001 THEN
        RAISE EXCEPTION 'CC_AJUSTE_ABAIXO_COMPROMETIDO: nova diferença (R$ %) menor que o já comprometido (R$ %) — revisão do financeiro necessária', v_new, v_committed;
      END IF;
      v_delta := round(v_new - v_open.valor_original, 2);
      IF v_delta <> 0 THEN
        v_tipo := CASE
          WHEN (v_open.direcao = 'FAVOR_CLIENTE' AND v_delta > 0) OR (v_open.direcao = 'FAVOR_EMPRESA' AND v_delta < 0) THEN 'CREDITO'
          ELSE 'DEBITO' END;
        INSERT INTO public.movimento_credito (id_cliente, id_int, valor, tipo, origem, observacao, created_by,
               id_pendencia, tipo_evento, id_int_origem, motivo_evento)
        VALUES (p_id_cliente, p_id_int, abs(v_delta), v_tipo, 'SISTEMA',
               'Ajuste de diferença da pendência (reconciliação).', v_uid,
               v_open.id, 'ABERTURA', p_id_int, p_motivo);
        UPDATE public.conta_corrente_pendencias
           SET valor_original = v_new, valor_saldo = valor_saldo + v_delta,
               status = public.cc__status(v_new, valor_saldo + v_delta, valor_reservado),
               atualizado_em = now()
         WHERE id = v_open.id;
        PERFORM public.cc__timeline(p_id_int, p_id_cliente,
          format('🔁 Pendência ajustada para R$ %s (%s).', to_char(v_new,'FM999999990.00'), v_open.direcao), v_uid);
      END IF;
      RETURN v_open.id;
    ELSE
      IF v_committed > 0 THEN
        RAISE EXCEPTION 'CC_FLIP_COM_COMPROMETIDO: inversão de direção com valor já usado/reservado — revisão do financeiro necessária';
      END IF;
      INSERT INTO public.movimento_credito (id_cliente, id_int, valor, tipo, origem, observacao, created_by,
             id_pendencia, tipo_evento, id_int_origem, motivo_evento)
      VALUES (p_id_cliente, p_id_int, v_open.valor_saldo,
             CASE WHEN v_open.direcao = 'FAVOR_CLIENTE' THEN 'DEBITO' ELSE 'CREDITO' END,
             'SISTEMA', 'Encerramento por inversão de direção.', v_uid,
             v_open.id, 'CANCELAMENTO', p_id_int, 'INVERSAO_DIRECAO');
      UPDATE public.conta_corrente_pendencias
         SET valor_saldo = 0, status = 'CANCELADA', encerrado_em = now(), encerrado_por = v_uid,
             motivo_encerramento = 'INVERSAO_DIRECAO', atualizado_em = now()
       WHERE id = v_open.id;
    END IF;
  END IF;

  IF v_new < 0.01 THEN RETURN NULL; END IF;
  INSERT INTO public.conta_corrente_pendencias
    (id_int, id_cliente, direcao, motivo, valor_original, valor_saldo, valor_reservado, status, chave_evento, observacao, created_by)
  VALUES (p_id_int, p_id_cliente, v_dir, p_motivo, v_new, v_new, 0, 'ABERTA', p_chave_evento, p_observacao, v_uid)
  RETURNING id INTO v_new_id;

  INSERT INTO public.movimento_credito (id_cliente, id_int, valor, tipo, origem, observacao, created_by,
         id_pendencia, tipo_evento, id_int_origem, motivo_evento)
  VALUES (p_id_cliente, p_id_int, v_new,
         CASE WHEN v_dir = 'FAVOR_CLIENTE' THEN 'CREDITO' ELSE 'DEBITO' END,
         'SISTEMA', 'Abertura de pendência por alteração de proposta paga.', v_uid,
         v_new_id, 'ABERTURA', p_id_int, p_motivo);

  PERFORM public.cc__timeline(p_id_int, p_id_cliente,
    format('🧾 Pendência aberta: R$ %s a favor de %s (motivo: %s).',
           to_char(v_new,'FM999999990.00'),
           CASE WHEN v_dir='FAVOR_CLIENTE' THEN 'cliente' ELSE 'empresa' END, p_motivo), v_uid);

  RETURN v_new_id;
END; $$;

-- =====================================================================================
-- SEÇÃO D.2 — RPC: cc_usar_pendencia
-- =====================================================================================
CREATE OR REPLACE FUNCTION public.cc_usar_pendencia(
  p_id_pendencia bigint, p_valor numeric, p_modo text,
  p_id_int_destino bigint DEFAULT NULL, p_id_pagamento uuid DEFAULT NULL,
  p_chave_reserva uuid DEFAULT NULL, p_observacao text DEFAULT NULL)
-- Retorna o id do lançamento em movimento_credito criado (CREDITO_IMEDIATO),
-- para permitir estorno pontual em rollback de consumo multi-pendência (FIFO)
-- feito pelo chamador. RESERVA_DEBITO não grava razão ainda — retorna NULL.
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_p public.conta_corrente_pendencias%ROWTYPE;
  v_pag public.pagamentos_v2%ROWTYPE;
  v_valor numeric; v_rem numeric; v_dummy int; v_movimento_id bigint;
BEGIN
  PERFORM public.cc__assert_permissao(v_uid, 'credito.usar');
  v_valor := round(p_valor, 2);
  IF v_valor < 0.01 THEN RAISE EXCEPTION 'CC_VALOR_MINIMO: uso mínimo é R$ 0,01'; END IF;

  SELECT * INTO v_p FROM public.conta_corrente_pendencias WHERE id = p_id_pendencia FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'CC_PENDENCIA: pendência % não encontrada', p_id_pendencia; END IF;
  IF v_p.status NOT IN ('ABERTA','PARCIALMENTE_RESOLVIDA') THEN
    RAISE EXCEPTION 'CC_STATUS: pendência não utilizável (status %)', v_p.status;
  END IF;

  -- Escopo de empresa da pendência (mesma regra oficial já usada no projeto).
  PERFORM public.cc__assert_escopo_empresa(v_uid, v_p.id_int);

  IF v_valor > v_p.valor_saldo THEN
    RAISE EXCEPTION 'CC_SALDO_INSUFICIENTE: saldo R$ % < solicitado R$ %', v_p.valor_saldo, v_valor;
  END IF;
  v_rem := round(v_p.valor_saldo - v_valor, 2);
  IF v_rem > 0 AND v_rem < 0.01 THEN RAISE EXCEPTION 'CC_RESIDUO: saldo residual entre R$ 0,00 e R$ 0,01 não é permitido'; END IF;

  IF p_modo = 'CREDITO_IMEDIATO' THEN
    IF v_p.direcao <> 'FAVOR_CLIENTE' THEN RAISE EXCEPTION 'CC_MODO: CREDITO_IMEDIATO exige direção FAVOR_CLIENTE'; END IF;
    UPDATE public.conta_corrente_pendencias
       SET valor_saldo = v_rem, status = public.cc__status(valor_original, v_rem, valor_reservado), atualizado_em = now()
     WHERE id = p_id_pendencia;
    INSERT INTO public.movimento_credito (id_cliente, id_int, valor, tipo, origem, observacao, created_by,
           id_pendencia, tipo_evento, id_int_origem, id_int_destino, id_pagamento_destino, motivo_evento)
    VALUES (v_p.id_cliente, v_p.id_int, v_valor, 'DEBITO', 'MANUAL',
           COALESCE(p_observacao,'Crédito aplicado como pagamento.'), v_uid,
           v_p.id, 'USO_PEDIDO', v_p.id_int, p_id_int_destino, p_id_pagamento, 'USO_CREDITO')
    RETURNING id INTO v_movimento_id;
    PERFORM public.cc__timeline(v_p.id_int, v_p.id_cliente,
      format('💰 Crédito de R$ %s aplicado como pagamento. Saldo restante: R$ %s.',
             to_char(v_valor,'FM999999990.00'), to_char(v_rem,'FM999999990.00')), v_uid);
    RETURN v_movimento_id;

  ELSIF p_modo = 'RESERVA_DEBITO' THEN
    IF v_p.direcao <> 'FAVOR_EMPRESA' THEN RAISE EXCEPTION 'CC_MODO: RESERVA_DEBITO exige direção FAVOR_EMPRESA'; END IF;
    IF p_id_pagamento IS NULL OR p_chave_reserva IS NULL THEN RAISE EXCEPTION 'CC_MODO: id_pagamento e chave_reserva são obrigatórios na reserva'; END IF;
    SELECT 1 INTO v_dummy FROM public.pagamentos_v2 WHERE chave_reserva = p_chave_reserva;
    IF FOUND THEN RETURN NULL; END IF;

    -- Trava o pagamento antes de decidir: nunca UPDATE às cegas. Rejeita
    -- CANCELADO, rejeita reserva já existente (nunca sobrescreve), e exige
    -- que pagamento e proposta de destino pertençam ao MESMO cliente e à
    -- mesma empresa da pendência.
    SELECT * INTO v_pag FROM public.pagamentos_v2 WHERE id = p_id_pagamento FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'CC_COBRANCA: pagamento % não encontrado para reserva', p_id_pagamento; END IF;
    IF v_pag.status = 'CANCELADO' THEN
      RAISE EXCEPTION 'CC_COBRANCA_CANCELADA: pagamento % está cancelado', p_id_pagamento;
    END IF;
    IF v_pag.id_pendencia IS NOT NULL OR v_pag.reserva_estado IS NOT NULL THEN
      RAISE EXCEPTION 'CC_RESERVA_EXISTENTE: pagamento % já está vinculado a outra reserva', p_id_pagamento;
    END IF;
    IF v_pag.id_cliente IS DISTINCT FROM v_p.id_cliente THEN
      RAISE EXCEPTION 'CC_CLIENTE_DIVERGENTE: pagamento % pertence a outro cliente', p_id_pagamento;
    END IF;
    IF p_id_int_destino IS NOT NULL AND v_pag.id_int IS DISTINCT FROM p_id_int_destino THEN
      RAISE EXCEPTION 'CC_PROPOSTA_DIVERGENTE: pagamento % não pertence à proposta de destino informada', p_id_pagamento;
    END IF;
    IF v_pag.id_empresa IS NOT NULL AND v_pag.id_empresa <> public.cc__id_empresa_proposta(v_p.id_int) THEN
      RAISE EXCEPTION 'CC_EMPRESA_DIVERGENTE: pagamento % pertence a outra empresa', p_id_pagamento;
    END IF;

    UPDATE public.conta_corrente_pendencias
       SET valor_saldo = v_rem, valor_reservado = valor_reservado + v_valor,
           status = public.cc__status(valor_original, v_rem, valor_reservado + v_valor), atualizado_em = now()
     WHERE id = p_id_pendencia;
    UPDATE public.pagamentos_v2
       SET id_pendencia = p_id_pendencia, valor_pendencia = v_valor,
           reserva_estado = 'RESERVA_ATIVA', chave_reserva = p_chave_reserva
     WHERE id = p_id_pagamento;
    PERFORM public.cc__timeline(v_p.id_int, v_p.id_cliente,
      format('📌 Débito de R$ %s reservado à cobrança do novo pedido (aguarda recebimento).',
             to_char(v_valor,'FM999999990.00')), v_uid);
    RETURN NULL;
  ELSE
    RAISE EXCEPTION 'CC_MODO: modo inválido %', p_modo;
  END IF;
END; $$;

-- =====================================================================================
-- SEÇÃO D.3 — RPC: cc_encerrar_pendencia
-- =====================================================================================
CREATE OR REPLACE FUNCTION public.cc_encerrar_pendencia(
  p_id_pendencia bigint, p_modo text, p_valor numeric DEFAULT NULL,
  p_id_movimento_ref bigint DEFAULT NULL, p_chave_reserva uuid DEFAULT NULL,
  p_motivo text DEFAULT NULL, p_observacao text DEFAULT NULL,
  p_id_pendencia_credito bigint DEFAULT NULL)
-- p_id_pendencia_credito: exclusivo do modo ABATER_DEBITO — pendência de
-- CRÉDITO (FAVOR_CLIENTE) consumida para baixar a pendência de DÉBITO
-- (p_id_pendencia, FAVOR_EMPRESA) na MESMA invocação/transação (ver bloco
-- ABATER_DEBITO abaixo — operação atômica, nunca duas chamadas separadas).
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_p public.conta_corrente_pendencias%ROWTYPE;
  v_cred public.conta_corrente_pendencias%ROWTYPE;
  v_res public.pagamentos_v2%ROWTYPE;
  v_ref public.movimento_credito%ROWTYPE;
  v_valor numeric; v_rem numeric; v_rem_cred numeric; v_tipo text; v_free numeric; v_mc_debito_id bigint;
BEGIN
  IF p_modo = 'CONFIRMAR_RESERVA' THEN
    -- Confirmação de recebimento é ato de conferência financeira, não de uso
    -- de crédito — exige a permissão correspondente (mesma já usada pela
    -- rota chamadora /api/cobrancas/confirmar).
    PERFORM public.cc__assert_permissao(v_uid, 'conferencia.confirm');
    SELECT * INTO v_res FROM public.pagamentos_v2
      WHERE chave_reserva = p_chave_reserva AND reserva_estado = 'RESERVA_ATIVA' AND id_pendencia = p_id_pendencia;
    IF NOT FOUND THEN RAISE EXCEPTION 'CC_RESERVA: reserva ativa não encontrada para a chave informada'; END IF;
    -- Só confirma o que realmente foi recebido — mesmo critério de
    -- cc__valor_pago (PAID, ou A_VENCER já confirmado).
    IF NOT (v_res.status = 'PAID' OR (v_res.status = 'A_VENCER' AND v_res.confirmado = true)) THEN
      RAISE EXCEPTION 'CC_NAO_RECEBIDO: pagamento % não está confirmado como recebido (status %)', v_res.id, v_res.status;
    END IF;
    SELECT * INTO v_p FROM public.conta_corrente_pendencias WHERE id = p_id_pendencia FOR UPDATE;
    IF v_res.id_cliente IS DISTINCT FROM v_p.id_cliente THEN
      RAISE EXCEPTION 'CC_CLIENTE_DIVERGENTE: pagamento % pertence a outro cliente', v_res.id;
    END IF;
    PERFORM public.cc__assert_escopo_empresa(v_uid, v_p.id_int);
    v_valor := v_res.valor_pendencia;
    UPDATE public.conta_corrente_pendencias
       SET valor_reservado = valor_reservado - v_valor,
           status = public.cc__status(valor_original, valor_saldo, valor_reservado - v_valor), atualizado_em = now()
     WHERE id = p_id_pendencia;
    INSERT INTO public.movimento_credito (id_cliente, id_int, valor, tipo, origem, observacao, created_by,
           id_pendencia, tipo_evento, id_int_origem, id_int_destino, id_pagamento_destino, motivo_evento)
    VALUES (v_p.id_cliente, v_p.id_int, v_valor, 'CREDITO', 'MANUAL',
           COALESCE(p_observacao,'Débito recebido na cobrança do novo pedido.'), v_uid,
           v_p.id, 'USO_PEDIDO', v_p.id_int, v_res.id_int, v_res.id, 'CONFIRMACAO_DEBITO');
    UPDATE public.pagamentos_v2 SET reserva_estado = 'RESERVA_CONFIRMADA' WHERE id = v_res.id;
    PERFORM public.cc__timeline(v_p.id_int, v_p.id_cliente,
      format('✅ Débito de R$ %s confirmado (recebido).', to_char(v_valor,'FM999999990.00')), v_uid);

  ELSIF p_modo = 'LIBERAR_RESERVA' THEN
    PERFORM public.cc__assert_permissao(v_uid, 'credito.usar');
    SELECT * INTO v_res FROM public.pagamentos_v2
      WHERE chave_reserva = p_chave_reserva AND reserva_estado = 'RESERVA_ATIVA' AND id_pendencia = p_id_pendencia;
    IF NOT FOUND THEN RAISE EXCEPTION 'CC_RESERVA: reserva ativa não encontrada'; END IF;
    SELECT * INTO v_p FROM public.conta_corrente_pendencias WHERE id = p_id_pendencia FOR UPDATE;
    IF v_res.id_cliente IS DISTINCT FROM v_p.id_cliente THEN
      RAISE EXCEPTION 'CC_CLIENTE_DIVERGENTE: pagamento % pertence a outro cliente', v_res.id;
    END IF;
    PERFORM public.cc__assert_escopo_empresa(v_uid, v_p.id_int);
    v_valor := v_res.valor_pendencia;
    UPDATE public.conta_corrente_pendencias
       SET valor_reservado = valor_reservado - v_valor, valor_saldo = valor_saldo + v_valor,
           status = public.cc__status(valor_original, valor_saldo + v_valor, valor_reservado - v_valor), atualizado_em = now()
     WHERE id = p_id_pendencia;
    UPDATE public.pagamentos_v2 SET reserva_estado = 'RESERVA_LIBERADA' WHERE id = v_res.id;
    PERFORM public.cc__timeline(v_p.id_int, v_p.id_cliente,
      format('↩️ Reserva de R$ %s liberada (cobrança falhou/cancelada). Débito volta a ficar disponível.',
             to_char(v_valor,'FM999999990.00')), v_uid);

  ELSIF p_modo IN ('DEVOLUCAO','BONIFICACAO','BAIXA') THEN
    PERFORM public.cc__assert_permissao(v_uid, CASE p_modo
      WHEN 'DEVOLUCAO' THEN 'financeiro.devolver'
      WHEN 'BONIFICACAO' THEN 'financeiro.bonificar'
      ELSE 'financeiro.resolver_credito' END);
    v_valor := round(p_valor, 2);
    IF v_valor < 0.01 THEN RAISE EXCEPTION 'CC_VALOR_MINIMO: mínimo R$ 0,01'; END IF;
    SELECT * INTO v_p FROM public.conta_corrente_pendencias WHERE id = p_id_pendencia FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'CC_PENDENCIA: não encontrada'; END IF;
    -- Guarda de direção: DEVOLUCAO é exclusiva de crédito ao cliente;
    -- BONIFICACAO/BAIXA são exclusivas de débito a favor da empresa. Sem esta
    -- checagem, ex. BONIFICACAO numa pendência FAVOR_CLIENTE aumentaria o
    -- crédito em vez de resolver um débito.
    IF p_modo = 'DEVOLUCAO' AND v_p.direcao <> 'FAVOR_CLIENTE' THEN
      RAISE EXCEPTION 'CC_MODO: DEVOLUCAO exige direção FAVOR_CLIENTE';
    END IF;
    IF p_modo IN ('BONIFICACAO','BAIXA') AND v_p.direcao <> 'FAVOR_EMPRESA' THEN
      RAISE EXCEPTION 'CC_MODO: % exige direção FAVOR_EMPRESA', p_modo;
    END IF;
    PERFORM public.cc__assert_escopo_empresa(v_uid, v_p.id_int);
    IF v_valor > v_p.valor_saldo THEN RAISE EXCEPTION 'CC_SALDO_INSUFICIENTE'; END IF;
    v_rem := round(v_p.valor_saldo - v_valor, 2);
    IF v_rem > 0 AND v_rem < 0.01 THEN RAISE EXCEPTION 'CC_RESIDUO'; END IF;
    v_tipo := CASE p_modo WHEN 'DEVOLUCAO' THEN 'DEBITO' ELSE 'CREDITO' END;
    UPDATE public.conta_corrente_pendencias
       SET valor_saldo = v_rem, status = public.cc__status(valor_original, v_rem, valor_reservado),
           atualizado_em = now(),
           encerrado_em = CASE WHEN v_rem = 0 AND valor_reservado = 0 THEN now() ELSE encerrado_em END,
           encerrado_por = CASE WHEN v_rem = 0 AND valor_reservado = 0 THEN v_uid ELSE encerrado_por END
     WHERE id = p_id_pendencia;
    INSERT INTO public.movimento_credito (id_cliente, id_int, valor, tipo, origem, observacao, created_by,
           id_pendencia, tipo_evento, id_int_origem, motivo_evento)
    VALUES (v_p.id_cliente, v_p.id_int, v_valor, v_tipo, 'MANUAL', p_observacao, v_uid,
           v_p.id, p_modo, v_p.id_int, p_motivo);
    PERFORM public.cc__timeline(v_p.id_int, v_p.id_cliente,
      format('%s de R$ %s registrada.', initcap(p_modo), to_char(v_valor,'FM999999990.00')), v_uid);

  ELSIF p_modo = 'ABATER_DEBITO' THEN
    -- Operação composta ATÔMICA (uma única invocação de RPC = uma única
    -- transação de banco): consome a pendência de CRÉDITO
    -- (p_id_pendencia_credito) para baixar a pendência de DÉBITO
    -- (p_id_pendencia). Substitui o padrão anterior de duas chamadas de RPC
    -- separadas (não atômicas entre si, com risco de estado parcialmente
    -- concluído). Se qualquer validação falhar após uma das duas pendências
    -- já ter sido lida/travada, o ROLLBACK implícito da função desfaz tudo —
    -- nunca fica em estado intermediário visível a outra sessão.
    PERFORM public.cc__assert_permissao(v_uid, 'financeiro.resolver_credito');
    v_valor := round(p_valor, 2);
    IF v_valor < 0.01 THEN RAISE EXCEPTION 'CC_VALOR_MINIMO: mínimo R$ 0,01'; END IF;
    IF p_id_pendencia_credito IS NULL THEN RAISE EXCEPTION 'CC_PARAMS: id_pendencia_credito é obrigatório em ABATER_DEBITO'; END IF;
    IF p_id_pendencia_credito = p_id_pendencia THEN RAISE EXCEPTION 'CC_PARAMS: pendência de débito e de crédito devem ser diferentes'; END IF;

    -- Ordem determinística de lock (menor id primeiro) evita deadlock entre
    -- abatimentos concorrentes que envolvam as duas mesmas pendências em ordem trocada.
    IF p_id_pendencia < p_id_pendencia_credito THEN
      SELECT * INTO v_p    FROM public.conta_corrente_pendencias WHERE id = p_id_pendencia         FOR UPDATE;
      SELECT * INTO v_cred FROM public.conta_corrente_pendencias WHERE id = p_id_pendencia_credito  FOR UPDATE;
    ELSE
      SELECT * INTO v_cred FROM public.conta_corrente_pendencias WHERE id = p_id_pendencia_credito  FOR UPDATE;
      SELECT * INTO v_p    FROM public.conta_corrente_pendencias WHERE id = p_id_pendencia          FOR UPDATE;
    END IF;
    IF v_p.id IS NULL THEN RAISE EXCEPTION 'CC_PENDENCIA: pendência de débito % não encontrada', p_id_pendencia; END IF;
    IF v_cred.id IS NULL THEN RAISE EXCEPTION 'CC_PENDENCIA: pendência de crédito % não encontrada', p_id_pendencia_credito; END IF;
    IF v_p.direcao <> 'FAVOR_EMPRESA' THEN RAISE EXCEPTION 'CC_MODO: ABATER_DEBITO exige pendência de débito com direção FAVOR_EMPRESA'; END IF;
    IF v_cred.direcao <> 'FAVOR_CLIENTE' THEN RAISE EXCEPTION 'CC_MODO: ABATER_DEBITO exige pendência de crédito com direção FAVOR_CLIENTE'; END IF;
    IF v_p.status NOT IN ('ABERTA','PARCIALMENTE_RESOLVIDA') THEN RAISE EXCEPTION 'CC_STATUS: pendência de débito não utilizável (status %)', v_p.status; END IF;
    IF v_cred.status NOT IN ('ABERTA','PARCIALMENTE_RESOLVIDA') THEN RAISE EXCEPTION 'CC_STATUS: pendência de crédito não utilizável (status %)', v_cred.status; END IF;
    IF v_p.id_cliente <> v_cred.id_cliente THEN
      RAISE EXCEPTION 'CC_CLIENTE_DIVERGENTE: crédito e débito devem pertencer ao mesmo cliente';
    END IF;
    PERFORM public.cc__assert_escopo_empresa(v_uid, v_p.id_int);
    PERFORM public.cc__assert_escopo_empresa(v_uid, v_cred.id_int);
    IF v_valor > v_p.valor_saldo THEN RAISE EXCEPTION 'CC_SALDO_INSUFICIENTE: saldo do débito R$ % < solicitado R$ %', v_p.valor_saldo, v_valor; END IF;
    IF v_valor > v_cred.valor_saldo THEN RAISE EXCEPTION 'CC_SALDO_INSUFICIENTE: saldo do crédito R$ % < solicitado R$ %', v_cred.valor_saldo, v_valor; END IF;

    v_rem := round(v_p.valor_saldo - v_valor, 2);
    IF v_rem > 0 AND v_rem < 0.01 THEN RAISE EXCEPTION 'CC_RESIDUO: saldo residual do débito entre R$ 0,00 e R$ 0,01 não é permitido'; END IF;
    v_rem_cred := round(v_cred.valor_saldo - v_valor, 2);
    IF v_rem_cred > 0 AND v_rem_cred < 0.01 THEN RAISE EXCEPTION 'CC_RESIDUO: saldo residual do crédito entre R$ 0,00 e R$ 0,01 não é permitido'; END IF;

    -- (1) Baixa a pendência de débito (empresa recebe via crédito do cliente).
    UPDATE public.conta_corrente_pendencias
       SET valor_saldo = v_rem, status = public.cc__status(valor_original, v_rem, valor_reservado),
           atualizado_em = now(),
           encerrado_em = CASE WHEN v_rem = 0 AND valor_reservado = 0 THEN now() ELSE encerrado_em END,
           encerrado_por = CASE WHEN v_rem = 0 AND valor_reservado = 0 THEN v_uid ELSE encerrado_por END
     WHERE id = v_p.id;
    INSERT INTO public.movimento_credito (id_cliente, id_int, valor, tipo, origem, observacao, created_by,
           id_pendencia, tipo_evento, id_int_origem, id_int_destino, motivo_evento)
    VALUES (v_p.id_cliente, v_p.id_int, v_valor, 'CREDITO', 'MANUAL', p_observacao, v_uid,
           v_p.id, 'BAIXA', v_p.id_int, v_cred.id_int, p_motivo)
    RETURNING id INTO v_mc_debito_id;

    -- (2) Consome a pendência de crédito na mesma proporção (efeito de "usar o
    -- crédito para pagar o débito"), referenciando o lançamento acima.
    UPDATE public.conta_corrente_pendencias
       SET valor_saldo = v_rem_cred, status = public.cc__status(valor_original, v_rem_cred, valor_reservado),
           atualizado_em = now(),
           encerrado_em = CASE WHEN v_rem_cred = 0 AND valor_reservado = 0 THEN now() ELSE encerrado_em END,
           encerrado_por = CASE WHEN v_rem_cred = 0 AND valor_reservado = 0 THEN v_uid ELSE encerrado_por END
     WHERE id = v_cred.id;
    INSERT INTO public.movimento_credito (id_cliente, id_int, valor, tipo, origem, observacao, created_by,
           id_pendencia, tipo_evento, id_int_origem, id_int_destino, id_movimento_ref, motivo_evento)
    VALUES (v_cred.id_cliente, v_cred.id_int, v_valor, 'DEBITO', 'MANUAL', p_observacao, v_uid,
           v_cred.id, 'DEVOLUCAO', v_cred.id_int, v_p.id_int, v_mc_debito_id, p_motivo);

    PERFORM public.cc__timeline(v_p.id_int, v_p.id_cliente,
      format('🔗 Débito de R$ %s abatido com crédito da proposta #%s.', to_char(v_valor,'FM999999990.00'), v_cred.id_int), v_uid);
    IF v_cred.id_int <> v_p.id_int THEN
      PERFORM public.cc__timeline(v_cred.id_int, v_cred.id_cliente,
        format('🔗 Crédito de R$ %s usado para abater débito da proposta #%s.', to_char(v_valor,'FM999999990.00'), v_p.id_int), v_uid);
    END IF;

  ELSIF p_modo = 'CANCELAMENTO' THEN
    PERFORM public.cc__assert_permissao(v_uid, 'financeiro.resolver_credito');
    SELECT * INTO v_p FROM public.conta_corrente_pendencias WHERE id = p_id_pendencia FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'CC_PENDENCIA: não encontrada'; END IF;
    PERFORM public.cc__assert_escopo_empresa(v_uid, v_p.id_int);
    IF v_p.valor_reservado > 0 THEN RAISE EXCEPTION 'CC_RESERVA_ATIVA: libere a reserva antes de cancelar'; END IF;
    v_free := v_p.valor_saldo;
    IF v_free > 0 THEN
      INSERT INTO public.movimento_credito (id_cliente, id_int, valor, tipo, origem, observacao, created_by,
             id_pendencia, tipo_evento, id_int_origem, motivo_evento)
      VALUES (v_p.id_cliente, v_p.id_int, v_free,
             CASE WHEN v_p.direcao = 'FAVOR_CLIENTE' THEN 'DEBITO' ELSE 'CREDITO' END,
             'MANUAL', p_observacao, v_uid, v_p.id, 'CANCELAMENTO', v_p.id_int, p_motivo);
    END IF;
    UPDATE public.conta_corrente_pendencias
       SET valor_saldo = 0, status = 'CANCELADA', encerrado_em = now(), encerrado_por = v_uid,
           motivo_encerramento = p_motivo, atualizado_em = now()
     WHERE id = p_id_pendencia;
    PERFORM public.cc__timeline(v_p.id_int, v_p.id_cliente,
      format('🚫 Pendência cancelada. Motivo: %s.', COALESCE(p_motivo,'—')), v_uid);

  ELSIF p_modo = 'ESTORNO' THEN
    PERFORM public.cc__assert_permissao(v_uid, '__ADMIN__');   -- v1: somente admin/superadmin
    IF p_id_movimento_ref IS NULL THEN RAISE EXCEPTION 'CC_ESTORNO: id_movimento_ref obrigatório'; END IF;
    SELECT * INTO v_ref FROM public.movimento_credito WHERE id = p_id_movimento_ref AND id_pendencia = p_id_pendencia;
    IF NOT FOUND THEN RAISE EXCEPTION 'CC_ESTORNO: movimento não encontrado na pendência'; END IF;
    IF v_ref.tipo_evento NOT IN ('USO_PEDIDO','DEVOLUCAO','BONIFICACAO','BAIXA') THEN
      RAISE EXCEPTION 'CC_ESTORNO: só é possível estornar eventos de resolução';
    END IF;
    SELECT * INTO v_p FROM public.conta_corrente_pendencias WHERE id = p_id_pendencia FOR UPDATE;
    PERFORM public.cc__assert_escopo_empresa(v_uid, v_p.id_int);
    INSERT INTO public.movimento_credito (id_cliente, id_int, valor, tipo, origem, observacao, created_by,
           id_pendencia, tipo_evento, id_int_origem, id_movimento_ref, motivo_evento)
    VALUES (v_p.id_cliente, v_p.id_int, v_ref.valor,
           CASE WHEN v_ref.tipo = 'CREDITO' THEN 'DEBITO' ELSE 'CREDITO' END,
           'MANUAL', p_observacao, v_uid, v_p.id, 'ESTORNO', v_p.id_int, p_id_movimento_ref, p_motivo);
    UPDATE public.conta_corrente_pendencias
       SET valor_saldo = valor_saldo + v_ref.valor,
           status = public.cc__status(valor_original, valor_saldo + v_ref.valor, valor_reservado),
           atualizado_em = now(), encerrado_em = NULL, encerrado_por = NULL
     WHERE id = p_id_pendencia;
    PERFORM public.cc__timeline(v_p.id_int, v_p.id_cliente,
      format('♻️ Estorno de R$ %s (movimento #%s). Saldo reaberto.', to_char(v_ref.valor,'FM999999990.00'), p_id_movimento_ref), v_uid);
  ELSE
    RAISE EXCEPTION 'CC_MODO: modo inválido %', p_modo;
  END IF;
END; $$;

