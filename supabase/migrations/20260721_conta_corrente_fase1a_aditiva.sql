-- =====================================================================================
-- SEÇÃO C.1 — Proteção real das 5 colunas novas de pagamentos_v2
--   CONFIRMADO no catálogo vivo (pré-voo): pagamentos_v2 tem policy RLS
--   permissiva (`geral`, USING true, WITH CHECK true) e GRANT de
--   INSERT/UPDATE/DELETE/TRUNCATE em NÍVEL DE TABELA para anon e
--   authenticated.
--
--   CORREÇÃO (achado da revisão): um REVOKE INSERT/UPDATE (coluna) por si só
--   NÃO bloqueia nada enquanto o GRANT INSERT/UPDATE de tabela inteira
--   continuar valendo — no modelo de privilégios do Postgres, privilégio de
--   tabela e de coluna são cumulativos (OR), nunca um restringe o outro. É
--   preciso primeiro revogar INSERT/UPDATE na TABELA INTEIRA de
--   anon/authenticated, e só então conceder de volta, coluna a coluna,
--   apenas os campos legados que devem continuar editáveis. DELETE/TRUNCATE
--   não são tocados aqui (não têm granularidade de coluna — ficam para o
--   cutover 1b, que endurece a tabela como um todo).
--
--   A lista de colunas legadas é obtida do catálogo vivo (information_schema),
--   não hardcoded — evita esquecer alguma coluna existente e quebrar
--   silenciosamente um INSERT/UPDATE legado por omissão.
--
--   As 5 colunas protegidas (id_pendencia, valor_pendencia, reserva_estado,
--   chave_reserva, chave_idempotencia) ficam de fora do re-GRANT, tanto em
--   INSERT quanto em UPDATE: nenhuma delas pode mais ser definida
--   diretamente por anon/authenticated, nem na criação nem depois. A única
--   via de escrita passa a ser RPC SECURITY DEFINER (roda como dono da
--   tabela, imune a este REVOKE):
--     - id_pendencia/valor_pendencia/reserva_estado/chave_reserva →
--       cc_usar_pendencia / cc_encerrar_pendencia (Seção D).
--     - chave_idempotencia → pgv2_registrar_chave_idempotencia (Seção C.2),
--       chamada por usar-credito/route.ts e pagamento-combinado/route.ts
--       logo após o INSERT do pagamento (que agora NÃO inclui mais
--       chave_idempotencia no payload).
-- =====================================================================================
REVOKE INSERT, UPDATE ON public.pagamentos_v2 FROM anon, authenticated;

DO $$
DECLARE
  v_cols text;
BEGIN
  SELECT string_agg(quote_ident(column_name), ', ' ORDER BY ordinal_position)
    INTO v_cols
  FROM information_schema.columns
  WHERE table_schema = 'public' AND table_name = 'pagamentos_v2'
    AND column_name NOT IN ('id_pendencia','valor_pendencia','reserva_estado','chave_reserva','chave_idempotencia');

  IF v_cols IS NULL THEN
    RAISE EXCEPTION 'CC_MIGRACAO: nenhuma coluna legada encontrada em pagamentos_v2 — abortando para não conceder 0 colunas';
  END IF;

  EXECUTE format('GRANT INSERT (%s) ON public.pagamentos_v2 TO anon, authenticated', v_cols);
  EXECUTE format('GRANT UPDATE (%s) ON public.pagamentos_v2 TO anon, authenticated', v_cols);
END $$;

-- =====================================================================================
-- SEÇÃO C.2 — RPC: pgv2_registrar_chave_idempotencia
--   Único caminho para gravar pagamentos_v2.chave_idempotencia. Chamada
--   pelas rotas logo após o INSERT do pagamento (que não inclui mais essa
--   coluna).
--
--   Autorização em duas camadas — NÃO confia somente em credito.usar
--   (permissão global, sem recorte por linha):
--     1) cc__assert_permissao(credito.usar) — baseline, igual às demais RPCs.
--     2) Escopo de empresa da linha — MESMA regra oficial já usada em
--        cancelar-boleto/route.ts e cancelar-externo/route.ts para
--        pagamentos_v2: super_adm passa; qualquer outro usuário só age sobre
--        um pagamento cujo id_empresa bate com usuarios.id_empresa. Sem essa
--        camada, qualquer usuário com credito.usar poderia carimbar a chave
--        de idempotência de um pagamento de OUTRA empresa/proposta.
--
--   Trava a linha com FOR UPDATE antes de decidir, rejeita pagamento
--   CANCELADO, e só grava se chave_idempotencia ainda estiver NULL (checado
--   explicitamente sobre a linha já travada — mesma regra de antes, sem
--   repetir a condição no WHERE do UPDATE). O índice único
--   ux_pgv2_chave_idempotencia continua sendo quem impede duas linhas
--   diferentes com a mesma chave — não removido, não substituído.
-- =====================================================================================
CREATE OR REPLACE FUNCTION public.pgv2_registrar_chave_idempotencia(
  p_id_pagamento uuid, p_chave_idempotencia uuid)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_pag public.pagamentos_v2%ROWTYPE;
  v_super public.usuarios.is_super_adm%TYPE;
  v_empresa_usuario public.usuarios.id_empresa%TYPE;
BEGIN
  PERFORM public.cc__assert_permissao(v_uid, 'credito.usar');
  IF p_id_pagamento IS NULL OR p_chave_idempotencia IS NULL THEN
    RAISE EXCEPTION 'MC_PARAMS: id_pagamento e chave_idempotencia são obrigatórios';
  END IF;

  SELECT * INTO v_pag FROM public.pagamentos_v2 WHERE id = p_id_pagamento FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'MC_PAGAMENTO: pagamento % não encontrado', p_id_pagamento;
  END IF;
  IF v_pag.status = 'CANCELADO' THEN
    RAISE EXCEPTION 'MC_CANCELADO: pagamento % está cancelado', p_id_pagamento;
  END IF;

  SELECT is_super_adm, id_empresa INTO v_super, v_empresa_usuario
    FROM public.usuarios WHERE user_id = v_uid;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'AUTH: usuário sem cadastro em public.usuarios' USING ERRCODE = '28000';
  END IF;
  IF COALESCE(v_super, false) = false THEN
    IF v_empresa_usuario IS NULL OR v_pag.id_empresa IS NULL OR v_empresa_usuario <> v_pag.id_empresa THEN
      RAISE EXCEPTION 'PERM: pagamento fora do escopo de empresa do usuário' USING ERRCODE = '42501';
    END IF;
  END IF;

  IF v_pag.chave_idempotencia IS NOT NULL THEN
    RAISE EXCEPTION 'MC_IDEMPOTENCIA: pagamento % já possui chave', p_id_pagamento;
  END IF;

  UPDATE public.pagamentos_v2
     SET chave_idempotencia = p_chave_idempotencia
   WHERE id = p_id_pagamento;
END; $$;

REVOKE ALL ON FUNCTION public.pgv2_registrar_chave_idempotencia(uuid,uuid) FROM public, anon;
GRANT EXECUTE ON FUNCTION public.pgv2_registrar_chave_idempotencia(uuid,uuid) TO authenticated;

